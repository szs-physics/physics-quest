KANA = "アイウエオカキクケコ"


def conv(s):
    """［ア　　］・［ウ］ → {{ア}}"""
    return re.sub(r"［([" + KANA + r"])[\s　]*］", r"{{\1}}", s)


BLANK = r"\{\{([" + KANA + r"])\}\}"


def build():
    """熱と同じ形の categories・items を返す（field は 'wave'、id は w単元-穴）"""
    cats, items = [], []
    for no, name, chunks in UNITS:
        cat = f"波{no}　{name}"
        start = len(items)
        seen = set()
        for ch in chunks:
            text = conv(ch)
            keys = re.findall(BLANK, text)
            fills = {k: A[no][k][0] for k in keys}
            for key in keys:
                if key in seen:
                    continue
                seen.add(key)
                ans, wr, exp = A[no][key]
                it = {"id": f"w{no}-{key}", "field": "wave", "cat": cat, "q": text, "blank": key,
                      "correct": ans, "wrongs": wr, "exp": exp, "fills": fills}
                if no in FIG and key in FIG[no]["for"]:
                    it["img"] = FIG[no]["img"]
                items.append(it)
        missing = set(A[no]) - seen
        assert not missing, (no, missing)
        cats.append({"name": cat, "field": "wave", "count": len(items) - start})
    return cats, items
