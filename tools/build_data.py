def conv(s):
    """〔^{n}　…〕 → {{n}}、〔①…〕 → {{①}}、e〔^{4}＞・＝・＜〕1 → {{4}}（m^{3} などの上付きと区別するため二重かっこ）"""
    s = re.sub(r"〔\^\{(\d+)\}[＞・＝＜]+〕", r"{{\1}}", s)
    s = re.sub(r"〔\^\{(\d+)\}[\s　]*〕", r"{{\1}}", s)
    s = re.sub(r"〔([①②])[\s　]*〕", r"{{\1}}", s)
    return s


